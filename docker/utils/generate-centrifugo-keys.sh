#!/bin/sh
#
# Generate local secrets for the Centrifugo beta overlay.
#
# Usage:
#   sh utils/generate-centrifugo-keys.sh
#   sh utils/generate-centrifugo-keys.sh --force
#   sh utils/generate-centrifugo-keys.sh --scale-only
#
# Writes docker/.env.centrifugo and/or docker/.env.centrifugo-scale with mode
# 600. Secret values are never printed.
#

set -e

script_dir=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
docker_dir=$(dirname "$script_dir")
env_file="$docker_dir/.env.centrifugo"
scale_env_file="$docker_dir/.env.centrifugo-scale"
force=false
scale_only=false

case "${1:-}" in
    --force)
        force=true
        ;;
    --scale-only)
        scale_only=true
        ;;
    "")
        ;;
    *)
        echo "Usage: sh utils/generate-centrifugo-keys.sh [--force|--scale-only]" >&2
        exit 1
        ;;
esac

if ! command -v openssl >/dev/null 2>&1; then
    echo "Error: openssl is required but not found." >&2
    exit 1
fi

if [ "$scale_only" != true ] && [ -f "$env_file" ] && [ "$force" != true ]; then
    echo "Error: $env_file already exists. Re-run with --force to replace it." >&2
    exit 1
fi

if [ "$scale_only" != true ] && [ -f "$scale_env_file" ] && [ "$force" != true ]; then
    echo "Error: $scale_env_file already exists. Re-run with --force or --scale-only." >&2
    exit 1
fi

read_env_value() {
    [ -f "$docker_dir/.env" ] || return 0
    grep "^$1=" "$docker_dir/.env" | head -n1 | cut -d= -f2- | tr -d "\r\"'"
}

postgres_host=$(read_env_value POSTGRES_HOST)
postgres_port=$(read_env_value POSTGRES_PORT)
postgres_db=$(read_env_value POSTGRES_DB)
postgres_host=${postgres_host:-db}
postgres_port=${postgres_port:-5432}
postgres_db=${postgres_db:-postgres}

umask 077
tmp_file="$env_file.tmp.$$"
scale_tmp_file="$scale_env_file.tmp.$$"
trap 'rm -f "$tmp_file" "$scale_tmp_file"' EXIT HUP INT TERM

backup_file() {
    if [ -f "$1" ]; then
        cp -p "$1" "$1.old"
        chmod 600 "$1.old"
    fi
}

redis_password=$(openssl rand -hex 24)

if [ "$scale_only" != true ]; then
    token_secret=$(openssl rand -hex 32)
    http_api_key=$(openssl rand -hex 32)
    auth_db_password=$(openssl rand -hex 24)
    outbox_db_password=$(openssl rand -hex 24)
    admin_password=$(openssl rand -hex 24)
    admin_secret=$(openssl rand -hex 32)

    backup_file "$env_file"

    cat >"$tmp_file" <<EOF
# Generated by utils/generate-centrifugo-keys.sh. Do not commit this file.
# Re-run with --force to replace all values. The previous file is kept as
# .env.centrifugo.old.

CENTRIFUGO_CLIENT_TOKEN_HMAC_SECRET_KEY=$token_secret
# To rotate the connection-token secret, set these to the previous secret and
# a Unix expiry timestamp before replacing the current secret.
# CENTRIFUGO_CLIENT_TOKEN_HMAC_PREVIOUS_SECRET_KEY=
# CENTRIFUGO_CLIENT_TOKEN_HMAC_PREVIOUS_SECRET_KEY_VALID_UNTIL=
CENTRIFUGO_HTTP_API_KEY=$http_api_key

# Database roles created by the centrifugo-migrate Compose service.
CENTRIFUGO_AUTH_DB_PASSWORD=$auth_db_password
CENTRIFUGO_OUTBOX_DB_PASSWORD=$outbox_db_password
CENTRIFUGO_AUTH_DATABASE_URL=postgresql://centrifugo_auth:$auth_db_password@$postgres_host:$postgres_port/$postgres_db
CENTRIFUGO_OUTBOX_DATABASE_URL=postgresql://centrifugo_outbox:$outbox_db_password@$postgres_host:$postgres_port/$postgres_db

# Admin UI is disabled by default. Uncomment both to enable it internally.
# CENTRIFUGO_ADMIN_PASSWORD=$admin_password
# CENTRIFUGO_ADMIN_SECRET=$admin_secret
EOF

    chmod 600 "$tmp_file"
    mv "$tmp_file" "$env_file"
    echo "Wrote $env_file (mode 600)."
fi

backup_file "$scale_env_file"

cat >"$scale_tmp_file" <<EOF
# Generated by utils/generate-centrifugo-keys.sh. Do not commit this file.
# Loaded only by docker-compose.centrifugo-scale.yml. The previous file is
# kept as .env.centrifugo-scale.old.
#
# The bundled Redis service is for local scale testing only. For production,
# point the addresses at an external Redis deployment and remove the local
# redis service from the scale overlay.

CENTRIFUGO_ENGINE_TYPE=redis
CENTRIFUGO_ENGINE_REDIS_ADDRESS=redis://redis:6379
CENTRIFUGO_ENGINE_REDIS_PASSWORD=$redis_password

CENTRIFUGO_BROKER_ENABLED=true
CENTRIFUGO_BROKER_TYPE=redis
CENTRIFUGO_BROKER_REDIS_ADDRESS=redis://redis:6379
CENTRIFUGO_BROKER_REDIS_PASSWORD=$redis_password

CENTRIFUGO_PRESENCE_MANAGER_ENABLED=true
CENTRIFUGO_PRESENCE_MANAGER_TYPE=redis
CENTRIFUGO_PRESENCE_MANAGER_REDIS_ADDRESS=redis://redis:6379
CENTRIFUGO_PRESENCE_MANAGER_REDIS_PASSWORD=$redis_password

# External Redis authentication and TLS options. Set these for every
# component (engine, broker, presence manager) that connects to Redis.
# CENTRIFUGO_ENGINE_REDIS_USER=
# CENTRIFUGO_BROKER_REDIS_USER=
# CENTRIFUGO_PRESENCE_MANAGER_REDIS_USER=
# CENTRIFUGO_ENGINE_REDIS_TLS_ENABLED=true
# CENTRIFUGO_BROKER_REDIS_TLS_ENABLED=true
# CENTRIFUGO_PRESENCE_MANAGER_REDIS_TLS_ENABLED=true
# CENTRIFUGO_ENGINE_REDIS_TLS_SERVER_NAME=
# CENTRIFUGO_BROKER_REDIS_TLS_SERVER_NAME=
# CENTRIFUGO_PRESENCE_MANAGER_REDIS_TLS_SERVER_NAME=
# For an external Redis, also replace the three redis://redis:6379 addresses
# with rediss://<host>:<port> and set the TLS flags above.
EOF

chmod 600 "$scale_tmp_file"
mv "$scale_tmp_file" "$scale_env_file"
echo "Wrote $scale_env_file (mode 600)."
